#!/usr/bin/env python3
"""Generate the MoonBit conformance test module from the extracted vectors.

Inputs:  rfc4475_vectors.json  (octets, produced by extract_rfc4475.py)
         rfc4475_expectations.json (verdicts, reviewed by hand)
Output:  rfc4475_test.mbt

Keeping the vectors as hex literals means the generated file is pure ASCII and
survives `moon fmt` unchanged, which is what makes the conformance suite auditable
in review.
"""

import json
import sys

VECTORS = "rfc4475_vectors.json"
EXPECTATIONS = "rfc4475_expectations.json"
OUT = "rfc4475_test.mbt"


def main():
    vectors = json.load(open(VECTORS, encoding="utf-8"))
    exp = {v["id"]: v for v in json.load(open(EXPECTATIONS, encoding="utf-8"))["vectors"]}

    missing = [v["id"] for v in vectors if v["id"] not in exp]
    if missing:
        print("missing expectations for: %s" % ", ".join(missing), file=sys.stderr)
        return 1

    lines = []
    a = lines.append
    a("// Generated by tools/gen_tests.py from rfc4475_vectors.json — do not edit by hand.")
    a("//")
    a("// Every octet in this file comes from RFC 4475 itself; the expected verdicts come")
    a("// from rfc4475_expectations.json, which is read off the prose of each section.")
    a("// Regenerate with:")
    a("//   python3 tools/extract_rfc4475.py --rfc rfc4475.txt --out-dir .")
    a("//   python3 tools/gen_tests.py")
    a("")
    a("/// One torture vector: its octets and the verdict the RFC requires.")
    a("struct Vector {")
    a("  id : String")
    a("  section : String")
    a("  expect : String")
    a("  hex : String")
    a("}")
    a("")
    a("let vectors : Array[Vector] = [")
    for v in vectors:
        e = exp[v["id"]]
        a(
            '  { id: "%s", section: "%s", expect: "%s", hex: "%s" },'
            % (v["id"], v["section"], e["expect"], v["hex"])
        )
    a("]")
    a("")
    a('test "RFC 4475 corpus: every asserted vector reaches its required verdict" {')
    a("  let failures : Array[String] = []")
    a("  let mut asserted = 0")
    a("  let mut policy = 0")
    a("  for v in vectors {")
    a('    if v.expect == "policy" {')
    a("      policy = policy + 1")
    a("      continue")
    a("    }")
    a("    asserted = asserted + 1")
    a("    let input = bytes_from_hex(v.hex)")
    a("    let a = analyze(input)")
    a("    let actual = a.verdict().to_string()")
    a("    if actual != v.expect {")
    a('      failures.push("\\{v.id}(\\{v.section}) expected \\{v.expect} got \\{actual}")')
    a("    }")
    a("  }")
    a("  if failures.length() > 0 {")
    a('    let mut msg = "\\{failures.length()} of \\{asserted} vectors failed:"')
    a("    for f in failures {")
    a('      msg = msg + " | " + f')
    a("    }")
    a("    fail(msg)")
    a("  }")
    a("  // Guard against a silently shrinking suite.")
    a("  assert_true(asserted >= 45)")
    a("  assert_eq(policy, 4)")
    a("}")
    a("")
    a('test "RFC 4475 corpus: accepted vectors round-trip byte-for-byte" {')
    a("  let failures : Array[String] = []")
    a("  for v in vectors {")
    a('    if v.expect != "well-formed" || v.id == "mpart01" {')
    a("      continue")
    a("    }")
    a("    let input = bytes_from_hex(v.hex)")
    a("    let a = analyze(input)")
    a("    match a.message() {")
    a("      Some(msg) => {")
    a("        // dblreq carries a second message after the first body; only the")
    a("        // consumed prefix is expected to round-trip.")
    a("        let consumed = msg.consumed()")
    a("        let rebuilt = to_bytes(msg)")
    a("        let prefix = input.view(start=0, end=consumed)")
    a("        if hex_of(rebuilt.view()) != hex_of(prefix.view()) {")
    a('          failures.push("\\{v.id}: round-trip mismatch")')
    a("        }")
    a("        if msg.trailing().length() > 0 && v.id != \"dblreq\" {")
    a('          failures.push("\\{v.id}: unexpected trailing octets")')
    a("        }")
    a("      }")
    a('      None => failures.push("\\{v.id}: did not parse")')
    a("    }")
    a("  }")
    a("  if failures.length() > 0 {")
    a('    let mut msg = "\\{failures.length()} round-trip failures:"')
    a("    for f in failures {")
    a('      msg = msg + " | " + f')
    a("    }")
    a("    fail(msg)")
    a("  }")
    a("}")
    a("")
    open(OUT, "w", encoding="utf-8").write("\n".join(lines))
    print("wrote %s (%d vectors, %d asserted)" % (OUT, len(vectors), sum(
        1 for v in vectors if exp[v["id"]]["expect"] != "policy")))
    return 0


if __name__ == "__main__":
    sys.exit(main())
